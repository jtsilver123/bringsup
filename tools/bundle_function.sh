#!/bin/sh
# Join the redesign edge function into one file for single-file deploys
# (Supabase dashboard editor or the Management API). Output: supabase/dist/redesign.ts
set -e
cd "$(dirname "$0")/.."
F=supabase/functions/redesign
mkdir -p supabase/dist
{
  echo "// Generated by tools/bundle_function.sh from $F. Edit the source files, not this one."
  grep '^import .*"npm:' $F/index.ts
  cat $F/extract.ts
  grep -v '^import ' $F/prompt.ts
  grep -v '^import ' $F/index.ts
} > supabase/dist/redesign.ts
echo "wrote supabase/dist/redesign.ts"
