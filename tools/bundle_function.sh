#!/bin/sh
# Join an edge function's files into one for single-file deploys (Supabase dashboard editor or the
# Management API). Usage: tools/bundle_function.sh [redesign|projects ...]  Output: supabase/dist/<name>.ts
# Helper modules come first with their imports stripped; index.ts keeps its npm: imports at the top.
set -e
cd "$(dirname "$0")/.."
mkdir -p supabase/dist
for NAME in ${@:-redesign projects}; do
  F=supabase/functions/$NAME
  {
    echo "// Generated by tools/bundle_function.sh from $F. Edit the source files, not this one."
    cat $F/*.ts | grep '^import .*"npm:' | sort -u
    for M in $F/*.ts; do
      [ "$(basename $M)" = index.ts ] && continue
      grep -v '^import ' $M
    done
    grep -v '^import ' $F/index.ts
  } > supabase/dist/$NAME.ts
  echo "wrote supabase/dist/$NAME.ts"
done
